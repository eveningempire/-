def set_cell(table, row, column, value):
    table.rows[row].cells[column].text = value


def para_after(anchor, text, style="Normal"):
    p = doc.add_paragraph(style=style)
    p.text = text
    anchor.addnext(p._p)
    return p._p


def para_before(anchor, text, style="Normal"):
    p = doc.add_paragraph(style=style)
    p.text = text
    anchor.addprevious(p._p)
    return p._p


def heading(text):
    for p in doc.paragraphs:
        if p.text == text:
            return p
    raise ValueError(text)


def add_case(before, title, case_id, priority, purpose, setup, steps, rule, note=""):
    h = doc.add_paragraph(title + "/" + case_id, style="Heading 4")
    before.addprevious(h._p)
    caption = doc.add_paragraph("表 0  " + title, style="文件正文")
    before.addprevious(caption._p)
    table_elm = deepcopy(TEMPLATE_TABLE)
    before.addprevious(table_elm)
    table = Table(table_elm, doc._body)
    set_cell(table, 0, 3, title)
    set_cell(table, 1, 3, case_id)
    set_cell(table, 1, 7, priority)
    set_cell(table, 2, 7, "现场交付版本（测试时填写）")
    set_cell(table, 3, 3, purpose)
    set_cell(table, 6, 3, setup)
    set_cell(table, 8, 3, rule)
    for i in range(4):
        op, expected = steps[i] if i < len(steps) else ("记录现场证据与偏差。", "实际结果和判定据实填写；未执行不得判通过。")
